package domain

// ActuatorState — состояние выходов Edge.
// Насос и УФ-лампа считаются постоянно включёнными (флаг в конфигурации),
// поэтому здесь только то, чем управляет Rule Engine.
type ActuatorState struct {
	Heating bool // подогрев включён (жёлтый светодиод)
	Alarm   bool // активна тревога (красный светодиод)
	Normal  bool // активных алертов нет (зелёный светодиод)
	SafeMode bool // система в безопасном режиме
}
